#!/usr/bin/env python3
"""Exact critical values for Lawshe's content validity ratio (CVR), one-tailed exact binomial (p = .5).

Method: Ayre & Scally (2014; IO-066) recalculation of Lawshe (1975; IO-065). For a panel of N raters, the critical
number of 'essential' ratings is the smallest n_e with P(X >= n_e | N, 0.5) <= alpha; CVR_critical = (2 n_e - N) / N.
Used by protocol_modified_delphi.md (the table there is generated by `python validation/lawshe.py --markdown`).
"""
from __future__ import annotations

import argparse
from fractions import Fraction
from math import comb


def tail_prob(N: int, k: int) -> Fraction:
    """Exact P(X >= k) for X ~ Binomial(N, 1/2)."""
    return Fraction(sum(comb(N, i) for i in range(k, N + 1)), 2 ** N)


def critical_essential(N: int, alpha: float = 0.05) -> int | None:
    """Smallest number of 'essential' ratings that is significant; None if even unanimity is not."""
    a = Fraction(alpha).limit_denominator(10 ** 6)
    for k in range(0, N + 1):
        if tail_prob(N, k) <= a:
            return k
    return None


def cvr(n_essential: int, N: int) -> float:
    return (2 * n_essential - N) / N


def critical_cvr(N: int, alpha: float = 0.05) -> float | None:
    k = critical_essential(N, alpha)
    return None if k is None else cvr(k, N)


def retain(n_essential: int, n_essential_or_useful: int, N: int, alpha: float = 0.05,
           min_share_essential_or_useful: float = 0.75) -> bool:
    """Delphi retention rule (ADR-0024 §6): CVR at or above the exact critical value AND >= 75% essential or useful."""
    k = critical_essential(N, alpha)
    return k is not None and n_essential >= k and n_essential_or_useful / N >= min_share_essential_or_useful


def table(n_min: int = 5, n_max: int = 40, alpha: float = 0.05) -> list[dict]:
    rows = []
    for N in range(n_min, n_max + 1):
        k = critical_essential(N, alpha)
        rows.append({"N": N, "n_essential_critical": k, "cvr_critical": None if k is None else round(cvr(k, N), 3),
                     "exact_p": None if k is None else float(tail_prob(N, k))})
    return rows


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--min", type=int, default=5)
    ap.add_argument("--max", type=int, default=40)
    ap.add_argument("--alpha", type=float, default=0.05)
    ap.add_argument("--markdown", action="store_true")
    a = ap.parse_args()
    rows = table(a.min, a.max, a.alpha)
    if a.markdown:
        print("| N responding | critical n essential | critical CVR | exact one-tailed p |")
        print("|---|---|---|---|")
        for r in rows:
            k = "not attainable" if r["n_essential_critical"] is None else r["n_essential_critical"]
            c = "—" if r["cvr_critical"] is None else f"{r['cvr_critical']:.3f}"
            p = "—" if r["exact_p"] is None else f"{r['exact_p']:.4f}"
            print(f"| {r['N']} | {k} | {c} | {p} |")
    else:
        for r in rows:
            print(r)


if __name__ == "__main__":
    main()
