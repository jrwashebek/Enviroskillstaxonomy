// Builds the production page of the prototype from the unbundled sources, which stay the source of truth:
//   app/assets/js/app.bundle.js (+ .map)  one minified ES module of main.js and everything it imports (esbuild)
//   app/assets/css/app.bundle.css         the screen stylesheets of the template, concatenated in order and minified
//   app/index.html                        production page: bundle, data/core.js in parallel, early data map, and the
//                                         site chrome and home page prerendered by running the real app in Chromium
//   app/dev.html                          development page: the same shell loading assets/js/main.js and each stylesheet
// Both pages come from tools/index.template.html. Data files and their loading (<script src> injection) are unchanged.
//
// Usage (from the repository root):
//   node prototype/public-ui/tools/build-app.mjs                 build everything
//   node prototype/public-ui/tools/build-app.mjs --no-prerender  skip Chromium; index.html gets empty chrome containers
//   node prototype/public-ui/tools/build-app.mjs --check         exit 1 if index.html is older than its sources
// Needs esbuild in tools/node_modules (cd prototype/public-ui/tools && npm ci --ignore-scripts) and Playwright for the
// prerender (the same one tools/check-rendered.mjs uses). Licence: Apache-2.0.
import { readFileSync, writeFileSync, existsSync, statSync, readdirSync } from "node:fs";
import { join, dirname, extname, normalize, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { createHash } from "node:crypto";
import { gzipSync } from "node:zlib";
import http from "node:http";
import vm from "node:vm";

const HERE = dirname(fileURLToPath(import.meta.url));
const UI = join(HERE, "..");
const APP = join(UI, "app");
const JS = join(APP, "assets", "js");
const CSS = join(APP, "assets", "css");
const TEMPLATE = join(HERE, "index.template.html");
const OUT_JS = join(JS, "app.bundle.js");
const OUT_CSS = join(CSS, "app.bundle.css");
const args = new Set(process.argv.slice(2));
const require = createRequire(import.meta.url);

const tpl = readFileSync(TEMPLATE, "utf8");
const styleBlock = /<!-- @@styles:[^>]*-->\n([\s\S]*?)<!-- @@\/styles -->\n/;
const styleHrefs = [...(tpl.match(styleBlock) || ["", ""])[1].matchAll(/href="([^"]+)"/g)].map((m) => m[1]);
if (!styleHrefs.length) throw new Error("index.template.html: no stylesheets between @@styles and @@/styles");

// ---------------------------------------------------------------- inputs and their hash (for --check)
function jsSources(dir = JS) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
    const p = join(dir, d.name);
    if (d.isDirectory()) return jsSources(p);
    return d.name.endsWith(".js") && !d.name.startsWith("app.bundle") && d.name !== "gallery.js" ? [p] : [];
  }).sort();
}
const inputs = [TEMPLATE, ...jsSources(), ...styleHrefs.map((h) => join(APP, h)), join(APP, "data", "core.js")];
const inputHash = createHash("sha256").update(inputs.map((f) => relative(UI, f) + "\0" + readFileSync(f, "utf8")).join("\0")).digest("hex").slice(0, 16);
const stamp = `<!-- Generated by tools/build-app.mjs from tools/index.template.html (inputs ${inputHash}). Do not edit: edit the template and the modules, then rebuild. -->`;

if (args.has("--check")) {
  const cur = existsSync(join(APP, "index.html")) ? readFileSync(join(APP, "index.html"), "utf8") : "";
  const ok = cur.includes(`(inputs ${inputHash})`) && existsSync(OUT_JS) && existsSync(OUT_CSS);
  console.log(ok ? `build-app: up to date (inputs ${inputHash})` : "build-app: app/index.html or the bundles are older than their sources. Run: node prototype/public-ui/tools/build-app.mjs");
  process.exit(ok ? 0 : 1);
}

// ---------------------------------------------------------------- 1. JavaScript bundle
let esbuild;
try { esbuild = require("esbuild"); } catch {
  console.error("build-app: esbuild is missing. Run: cd prototype/public-ui/tools && npm ci --ignore-scripts");
  process.exit(2);
}
const banner = "/* EMST public-interface prototype. Licence: Apache-2.0. Built by tools/build-app.mjs from assets/js/main.js and its imports; edit those modules, not this file. */";
const js = await esbuild.build({
  entryPoints: [join(JS, "main.js")], outfile: OUT_JS, bundle: true, format: "esm", minify: true, target: "es2020",
  sourcemap: "linked", sourcesContent: false, charset: "utf8", legalComments: "none", banner: { js: banner },
  metafile: true, logLevel: "warning",
});
const bundled = Object.keys(js.metafile.inputs).length;

// ---------------------------------------------------------------- 2. stylesheet bundle (same files, same order)
const cssSrc = styleHrefs.map((h) => `/* ${h} */\n` + readFileSync(join(APP, h), "utf8")).join("\n");
const css = await esbuild.transform(cssSrc, { loader: "css", minify: true, legalComments: "none", charset: "utf8" });
writeFileSync(OUT_CSS, `/* EMST public-interface prototype. Built by tools/build-app.mjs from ${styleHrefs.map((h) => h.split("/").pop()).join(", ")}; edit those files, not this one. */\n` + css.code);

// ---------------------------------------------------------------- 3. early data map, from the same naming rules as lib/data.js
globalThis.window = {};
vm.runInThisContext(readFileSync(join(APP, "data", "core.js"), "utf8"));
const core = window.EMSTDATA.core;
const pad = (n) => String(n).padStart(2, "0");
const early = new Map(); // file -> [route, ...]; boot.js starts the file when the route is (or begins with) one of them
const add = (file, route) => { if (existsSync(join(APP, "data", `${file}.js`))) (early.get(file) || early.set(file, []).get(file)).push(route); };
for (const r of core.roles) add(core.files?.role?.[r.slug] || `role-${r.slug}`, `/role/${r.slug}`);
for (const [slug, n] of Object.entries(core.shards?.comp || {})) add(core.files?.comp?.[n] || `comp-${pad(n)}`, `/competency/${slug}`);
for (const route of ["/changing"]) add("change", route);
for (const route of ["/hr", "/series", "/classes", "/class"]) add("hr", route);
const earlyMeta = `<meta name="emst-early-data" content="${[...early].map(([f, rs]) => `${f}=${rs.join(",")}`).join(" ")}">`;

// ---------------------------------------------------------------- 4. pages
const devPage = tpl.replace(/<!-- @@build:[^>]*-->\n/, "<!-- Development page: loads the unbundled modules (assets/js/main.js) and each stylesheet. Generated by tools/build-app.mjs. -->\n")
  .replace(/<!-- @@styles:[^>]*-->\n/, "").replace("<!-- @@/styles -->\n", "")
  .replace("<!-- @@early-data -->\n", "").replace(/\n *<!-- @@prerender:main -->/, "").replace(/<!-- @@prerender:\w+ -->/g, "");
function prodPage({ top = "", main = "", bottom = "" } = {}) {
  return tpl.replace(/<!-- @@build:[^>]*-->/, stamp)
    .replace(styleBlock, '<link rel="stylesheet" href="assets/css/app.bundle.css">\n')
    .replace("<!-- @@early-data -->", earlyMeta)
    .replace('src="assets/js/main.js"', 'src="assets/js/app.bundle.js"')
    .replace("<!-- @@prerender:top -->", top).replace("<!-- @@prerender:bottom -->", bottom)
    .replace("<!-- @@prerender:main -->", main);
}
writeFileSync(join(APP, "dev.html"), devPage);

// ---------------------------------------------------------------- 5. prerender: run the real (bundled) app and copy what it renders
let pre = {};
if (!args.has("--no-prerender")) {
  const stage1 = prodPage();
  const TYPES = { ".html": "text/html; charset=utf-8", ".css": "text/css", ".js": "text/javascript", ".woff2": "font/woff2", ".svg": "image/svg+xml", ".json": "application/json", ".map": "application/json" };
  const server = http.createServer((req, res) => {
    const p = decodeURIComponent(req.url.split("?")[0]);
    if (p === "/__prerender.html") { res.writeHead(200, { "Content-Type": TYPES[".html"] }); return res.end(stage1); }
    const f = join(APP, normalize(p));
    if (!f.startsWith(APP) || !existsSync(f) || statSync(f).isDirectory()) { res.writeHead(404); return res.end(); }
    res.writeHead(200, { "Content-Type": TYPES[extname(f)] || "application/octet-stream" });
    res.end(readFileSync(f));
  });
  await new Promise((ok) => server.listen(0, "127.0.0.1", ok));
  const base = `http://127.0.0.1:${server.address().port}`;
  const { chromium } = require("playwright");
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  const problems = [];
  page.on("pageerror", (e) => problems.push(e.message));
  page.on("console", (m) => { if (m.type() === "error") problems.push(m.text()); });
  page.on("request", (r) => { if (!r.url().startsWith(base)) problems.push(`external request ${r.url()}`); });
  await page.goto(`${base}/__prerender.html#/`);
  await page.waitForFunction(() => !document.querySelector("#main[aria-busy]") && document.querySelector("#main > .container h1") && document.querySelector("#site-top .site-header") && document.querySelector("#site-bottom .site-footer"), null, { timeout: 30000 });
  await page.waitForTimeout(300);
  pre = await page.evaluate(() => {
    // Serialise a copy, marked so boot.js and the one CSS rule in app.css can tell prerendered markup from live markup.
    const mark = (el, v) => { const c = el.cloneNode(true); c.setAttribute("data-prerender", v); return c.outerHTML; };
    return {
      top: [...document.querySelector("#site-top").children].map((e) => mark(e, "chrome")).join("\n"),
      bottom: [...document.querySelector("#site-bottom").children].map((e) => mark(e, "chrome")).join("\n"),
      main: mark(document.querySelector("#main > .container"), "home"),
    };
  });
  await browser.close();
  server.close();
  if (problems.length) { console.error("build-app: the app reported problems while prerendering:\n  " + problems.join("\n  ")); process.exit(1); }
  // The same markup lib/router.js shows while a slow route loads; app.css shows it only on deep links.
  pre.main += '\n    <div class="container" data-prerender="loading"><div class="loading" role="status"><span class="spinner" aria-hidden="true"></span>Loading…</div></div>';
}
const index = prodPage(pre);
writeFileSync(join(APP, "index.html"), index);

// ---------------------------------------------------------------- report
const kb = (b) => (b / 1024).toFixed(1);
const size = (f) => { const b = readFileSync(f); return { raw: b.length, gz: /\.woff2$/.test(f) ? b.length : gzipSync(b, { level: 6 }).length }; };
const rows = [["index.html", join(APP, "index.html")], ["app.bundle.js", OUT_JS], ["app.bundle.css", OUT_CSS], ["boot.js", join(JS, "boot.js")],
  ["fonts (400, 600, serif)", ["public-sans-400", "public-sans-600", "Latin-Merriweather-Regular"].map((f) => join(APP, "assets", "fonts", `${f}.woff2`))], ["icons.svg", join(APP, "assets", "icons.svg")]];
let total = 0;
console.log(`build-app: bundled ${bundled} modules; prerender ${pre.top ? "on" : "off"}; inputs ${inputHash}`);
for (const [name, f] of rows) {
  const s = [f].flat().map(size).reduce((a, b) => ({ raw: a.raw + b.raw, gz: a.gz + b.gz }));
  total += s.gz;
  console.log(`  ${name.padEnd(24)} ${kb(s.raw).padStart(7)} KB raw ${kb(s.gz).padStart(7)} KB gzip`);
}
console.log(`  ${"app shell total".padEnd(24)} ${"".padStart(14)} ${kb(total).padStart(7)} KB gzip (budget 200)`);
