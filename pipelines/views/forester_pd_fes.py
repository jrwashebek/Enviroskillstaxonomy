#!/usr/bin/env python3
"""Regenerate the v1 Forester PD prototype (legacy/v1/docs/forester_pd_transformation.html) from v2 data in FES format.

Source records: seed:R14-forester and its federal variant (bundle + adds - drops, journey level, the GS-9 to GS-11
band that the v1 prototype's GS-0460-09/11 position sits in), competency targets and knowledge statements, the 0460
SeriesRecord, the L1-L5 attribute definitions (vocab/proficiency_levels.yaml, which name their FES parallels) and task
field dependency. Factor levels and points are deliberately left to the classifier: this is a draft "subject to
classification review", not a classification. v1 duty percentages and exposure calls are not reused (Q7; ADR-0027).
Output: docs/package/forester_pd_fes_draft.md (for WP-14). Licence of the output: CC BY 4.0 (publication); code Apache-2.0.
"""
from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import viewlib as V  # noqa: E402

GEN = "pipelines/views/forester_pd_fes.py@0.1.0"
OUT = V.ROOT / "docs" / "package" / "forester_pd_fes_draft.md"
LEVEL = "journey"
MERGE_BELOW = 8


def short(s, n=110):
    s = s.rstrip(".")
    return s if len(s) <= n else s[:s.rfind(" ", 0, n)].rstrip(",;:") + "…"


def attr(levels_vocab, level, key):
    for t in levels_vocab["terms"]:
        if t.get("notation") == level:
            return (t.get("descriptors") or {}).get(key, "")
    return ""


def main():
    d = V.Data()
    role = d.get("seed:R14-forester")
    var = d.get("seed:R14-forester/federal")
    ser = d.series["0460"]
    pv = V.L.load_yaml(V.ROOT / "vocab" / "proficiency_levels.yaml")
    band = dict((lv[0], b) for b, lv in V.parse_band(var["indicativeGradeOrBand"]["band"]) if lv).get(LEVEL)
    items = V.at_levels(V.effective_bundle(role, var), [LEVEL])
    duties = V.duties(d, role, items)
    major = [x for x in duties if x["pctTime"] >= MERGE_BELOW]
    minor = [x for x in duties if x["pctTime"] < MERGE_BELOW]
    tg = V.targets_at(d, role, [LEVEL])
    lv = [t["targetLevels"][LEVEL] for t in tg if t["importance"] >= 4]
    typical = Counter(lv).most_common(1)[0][0] if lv else "L2"
    upper = "L3"
    field = Counter((d.get(i["task"]) or {}).get("fieldDependency") for i in items)
    tot = sum(field.values()) or 1
    onsite = round(100 * sum(i["shareWithin"] for i in items if (d.get(i["task"]) or {}).get("fieldDependency") == "on-site-required"))
    contacts = [i for i in items if any(w in d.statement(i["task"]).lower() for w in
                                        ("landowner", "permittee", "contract", "purchaser", "consulting", "cooperating", "public", "partner"))]
    entry = [i for i in items if i.get("neededAtEntry")]
    crit = [i for i in items if i.get("critical")]
    lines = [
        "# Forester, GS-0460 — position description (FES format), regenerated from EMST v2 data",
        "",
        "> **DRAFT — SUBJECT TO CLASSIFICATION REVIEW.** Not a classification basis / not a job analysis / not for RIF or "
        "rating decisions. Generated from agent-drafted EMST v2 records (raterType llm, validationStatus draft, evidence S); "
        "no human has reviewed the duties, percentages or flags. Factor levels and points are left blank for the servicing "
        "classifier. Grade band is indicative only and is not a classification criterion.",
        "",
        f"- **Series:** 0460 {ser['prefLabel']['en']} — status: {('active' if ser.get('seriesStatus') == 'active' else ser.get('seriesStatus'))} "
        f"in the EMST OPM series register as of {V.AS_OF} (`{ser['id']}`, re-check by {ser.get('reviewBy')}).",
        f"- **Indicative band:** {band} (EMST role level: {LEVEL}; {typical}–{upper} on the EMST scale). Not a classification criterion.",
        "- **Organization:** [to be completed by the servicing HR office: agency, unit, duty station].",
        f"- **Positive education requirement:** {'yes' if ser.get('positiveEducationRequirement') else 'no'} for series 0460 "
        "(FH judgment pending verification against the current qualification standard).",
        f"- **Source records:** `{role['id']}`, `{var['id']}`; generated by `{GEN}` on {V.AS_OF}. Supersedes the v1 prototype "
        "`legacy/v1/docs/forester_pd_transformation.html` as the package version; v1 duty percentages and exposure calls "
        "are not reused (methodology history only).",
        "",
        "## Introduction",
        "",
        f"{role['functionStatement']['en']} {role['definition']['en']}",
        "",
        "## Major duties",
        "",
        "Percentages are indicative shares of time at the journey level, computed from the draft task bundle "
        "(time shares renormalized within the level). They are agent drafts, not job-analysis results.",
        "",
    ]
    n = 1
    for du in major:
        lines.append(f"### {n}. {du['duty']} ({du['pctTime']}%)")
        lines.append("")
        lines.append(" ".join(t["statement"].rstrip(".") + "." for t in du["tasks"][:5]))
        flags = [t for t in du["tasks"] if t["critical"] or t["neededAtEntry"]]
        if flags:
            lines.append("")
            lines.append("*Critical or needed-at-entry tasks in this duty (draft flags):* " +
                         "; ".join(short(t["statement"], 90) for t in flags[:4]) + ".")
        lines.append("")
        n += 1
    if minor:
        pct = sum(x["pctTime"] for x in minor)
        lines += [f"### {n}. Related duties ({pct}%)", "",
                  "Performs related work in: " + "; ".join(f"{x['duty'][0].lower()}{x['duty'][1:]} ({x['pctTime']}%)" for x in minor) + ".", ""]
    lines += ["## Factor 1 — Knowledge required by the position", "",
              "*Draft knowledge statements, from the role's competency targets at the journey level. Level: [classifier].*", ""]
    for t in tg:
        if t["importance"] < 4 and not t["distinguishing"]:
            continue
        lines.append(f"- Knowledge of and skill to {t['label'][0].lower()}{t['label'][1:]} (EMST {t['targetLevels'][LEVEL]})"
                     + (" — distinguishing for this position." if t["distinguishing"] else "."))
        for ks in [k["statement"]["en"] for k in d.ks_by_comp.get(t["competency"], [])][:2]:
            lines.append(f"  - {ks}")
    lines += ["- Knowledge of the agency's environmental review procedures, stewardship contracting and partner-agreement "
              "authorities as they apply to forest management projects (instruments linked on the variant: " +
              ", ".join(d.label(i) for i in var.get("instruments") or []) + ").", "",
              "## Factor 2 — Supervisory controls", "", "*Level: [classifier].*", "",
              f"{attr(pv, typical, 'ATT-AUT')} At the upper end of the band: {attr(pv, upper, 'ATT-AUT').lower()} "
              "The supervisor sets objectives, priorities and deadlines; completed prescriptions, cruises and sale packages "
              "are reviewed for conformance with plans and policy.", "",
              "## Factor 3 — Guidelines", "", "*Level: [classifier].*", "",
              f"{attr(pv, typical, 'ATT-GUI')} At the upper end: {attr(pv, upper, 'ATT-GUI').lower()} Guidelines include "
              "the land management plan, agency silvicultural and timber-sale manuals and handbooks, inventory protocols, "
              "contract specifications and the agency's environmental review procedures. For AI-assisted and remotely "
              f"sensed products, the incumbent {attr(pv, typical, 'ATT-AUG')[0].lower()}{attr(pv, typical, 'ATT-AUG')[1:]}", "",
              "## Factor 4 — Complexity", "", "*Level: [classifier].*", "",
              f"{attr(pv, typical, 'ATT-CPX')} At the upper end: {attr(pv, upper, 'ATT-CPX').lower()} Prescriptions must "
              "balance timber, habitat, fire risk, water and carbon objectives on stands whose structure, history and health "
              "vary; inventory designs must reconcile plot data with lidar and imagery products.", "",
              "## Factor 5 — Scope and effect", "", "*Level: [classifier].*", "",
              f"{attr(pv, typical, 'ATT-SCO')} At the upper end: {attr(pv, upper, 'ATT-SCO').lower()} The work determines "
              "how stands are treated and how sales are laid out and administered, which affects resource conditions for "
              "decades and the agency's contract and environmental compliance record.", "",
              "## Factor 6 — Personal contacts", "", "*Level: [classifier].*", "",
              "Contacts are with other resource specialists, contract purchasers and operators, partner organizations, "
              "landowners and the public in the field and in meetings. Draft tasks involving these contacts: " +
              "; ".join(short(d.statement(i["task"]), 90) for i in contacts[:5]) + ".", "",
              "## Factor 7 — Purpose of contacts", "", "*Level: [classifier].*", "",
              "To plan and coordinate work, explain prescriptions and contract requirements, resolve operational "
              "problems with purchasers and partners, and secure compliance with contract specifications and best "
              "management practices.", "",
              "## Factor 8 — Physical demands", "", "*Level: [classifier].*", "",
              f"About {onsite}% of the draft journey-level time share is in tasks whose performance requires being on site "
              "(`fieldDependency: on-site-required`). Field work involves walking long distances over steep, rough and "
              "brushy terrain in all seasons, carrying equipment, and climbing over down timber.", "",
              "## Factor 9 — Work environment", "", "*Level: [classifier].*", "",
              "Field work exposes the incumbent to weather extremes, hazard trees, active logging and equipment operations, "
              "insects, wildlife and remote locations with limited communication; protective equipment and the agency's "
              "field safety procedures apply. Office work is in an adequately lighted and ventilated setting.", "",
              "## Other information (EMST)", "",
              "- **Needed at entry (draft flags):** " + "; ".join(short(d.statement(i["task"]), 80) for i in entry[:8]) + ".",
              "- **Critical tasks (draft flags):** " + "; ".join(short(d.statement(i["task"]), 80) for i in crit[:8]) + ".",
              "- **Credential gates (draft; shown as fact only once sourced):** " +
              ("; ".join(f"{d.label(g['credential'])} ({g['kind']})" for g in var.get("credentialGates") or []) or "none recorded for the federal variant") + ".",
              "- **Selective placement or quality-ranking factors:** none. EMST v2.0 content is never used for selection "
              "(use tiers describe and develop only).",
              "- **How the work is changing:** no v2 multi-rater assessment exists for these tasks yet (\"assessment pending\"). "
              "The v1 prototype's time-reallocation figures were single-analyst estimates and are methodology history only.",
              "- **Formation tasks (draft flags):** " + ("; ".join(short(d.statement(i["task"]), 80) for i in items if i.get("formationTask"))
                                                      or "none flagged") + ". Keep unaided repetitions of these in development "
              "plans so that entry foresters build field judgment (ADR-0026; WP-07 provisions).",
              "",
              "---",
              "DRAFT — SUBJECT TO CLASSIFICATION REVIEW. Not a classification basis / not a job analysis / not for RIF or "
              "rating decisions.", ""]
    V.write_text(OUT, "\n".join(lines))
    print(f"wrote {OUT.relative_to(V.ROOT)}: {len(major)} major duties + related duties; journey band {band}")


if __name__ == "__main__":
    main()
