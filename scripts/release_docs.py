#!/usr/bin/env python3
"""Copy a release build's human-readable files into docs/release/<version>/ and generate the listings that go with them
(WP-16; ADR-0031 §9). Nothing here is typed: every number and row comes from the built release in dist/<version>/.

Writes, in docs/release/<version>/:
  RELEASE_NOTES.md   byte copy of dist/<version>/RELEASE_NOTES.md (generated by scripts/build_release.py#notes)
  counts.json        byte copy of dist/<version>/views/counts.json (counts rule, generated)
  delta_v1.json      byte copy of dist/<version>/delta_v1.json (delta against the v1 baseline, generated)
  PATHWAYS.md        listing of the released Pathway records (replaces the stale docs/build/WP-07/PATHWAYS.md for readers
                     of this release; that file belongs to a frozen builder, ADR-0030 §5)
  BUILD.md           version, release date, build commit, SHA-256 of SHA256SUMS and of the bundle

Usage: python scripts/release_docs.py --version 2.0.0-rc.1 [--dist dist/2.0.0-rc.1]
       python scripts/release_docs.py --version 2.0.0-rc.1 --check   # exit 1 if docs/release/<version>/ is stale
Licence: Apache-2.0.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import emstlib as L  # noqa: E402

COPIES = {"RELEASE_NOTES.md": "RELEASE_NOTES.md", "counts.json": "views/counts.json", "delta_v1.json": "delta_v1.json"}


def label(rec):
    pl = (rec or {}).get("prefLabel") or {}
    return pl.get("en") if isinstance(pl, dict) else str(pl)


def pathways_md(version, bundle):
    g = [r for r in bundle["@graph"] if isinstance(r, dict) and "id" in r]
    idx = {r["id"]: r for r in g}
    ps = sorted((r for r in g if r.get("type") == "Pathway"), key=lambda r: (
        next((n.get("value") for n in r.get("notation") or [] if n.get("scheme") == "mvp-corridor"), ""), r["id"]))
    out = [f"# EMST {version}: released pathways (generated)", "",
           f"Generated by `scripts/release_docs.py` from `dist/{version}/emst.bundle.jsonld`; do not edit by hand. "
           "Pathways are exploratory learning routes between roles; none is recommended until CM's M-03 gate passes "
           "(ADR-0023 §5). They are for training and development only, never for selection.", "",
           "| Pathway ID | Label | Corridor | Type | From → to | Steps | Tasks | CLOs | Formation provisions | Recommended | Use tier |",
           "|---|---|---|---|---|---|---|---|---|---|---|"]
    tot = {"steps": 0, "prov": 0}
    for p in ps:
        seq = p.get("sequence") or []
        tasks = {t for s in seq for t in (s.get("tasks") or [])}
        prov = sum(len(s.get("formationProvisions") or []) for s in seq)
        tot["steps"] += len(seq)
        tot["prov"] += prov
        cor = next((n.get("value") for n in p.get("notation") or [] if n.get("scheme") == "mvp-corridor"), "")
        frm, to = p.get("fromVariant"), p.get("toVariant")
        out.append(f"| `{p['id']}` | {label(p)} | {cor} | {p.get('pathwayType', '')} | "
                   f"{label(idx.get(frm)) or frm} → {label(idx.get(to)) or to} | {len(seq)} | {len(tasks)} | "
                   f"{len(p.get('cloOutcomes') or [])} | {prov} | {'yes' if p.get('recommended') else 'no'} | {p.get('useTier', '')} |")
    out += ["", f"Totals: {len(ps)} pathways, {tot['steps']} steps, {tot['prov']} formation provisions.", ""]
    return "\n".join(out)


def build_md(version, dist):
    sums = (dist / "SHA256SUMS").read_bytes()
    bsha = hashlib.sha256((dist / "emst.bundle.jsonld").read_bytes()).hexdigest()
    notes = (dist / "RELEASE_NOTES.md").read_text(encoding="utf-8").splitlines()
    released = next((ln for ln in notes if ln.startswith("- Released:")), "- Released: (not stated)")
    return "\n".join([
        f"# EMST {version}: build record (generated)", "",
        f"Generated by `scripts/release_docs.py` from `dist/{version}/`; do not edit by hand.", "",
        released, f"- SHA-256 of `SHA256SUMS`: `{hashlib.sha256(sums).hexdigest()}`",
        f"- SHA-256 of `emst.bundle.jsonld`: `{bsha}`",
        f"- Files listed in `SHA256SUMS`: {len(sums.decode('utf-8').splitlines())}", "",
        "The release build is deterministic: two builds of the same tree are byte-identical (`diff -r`). A build made "
        "after the orchestrator commits will carry that commit in its build line, so its hashes differ from these.", ""])


def render(version, dist):
    bundle = json.loads((dist / "emst.bundle.jsonld").read_text(encoding="utf-8"))
    files = {name: (dist / src).read_bytes() for name, src in COPIES.items()}
    files["PATHWAYS.md"] = pathways_md(version, bundle).encode("utf-8")
    files["BUILD.md"] = build_md(version, dist).encode("utf-8")
    return files


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--version", required=True)
    ap.add_argument("--dist", type=Path)
    ap.add_argument("--out", type=Path)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    dist = a.dist or (L.ROOT / "dist" / a.version)
    out = a.out or (L.ROOT / "docs" / "release" / a.version)
    files = render(a.version, dist)
    if a.check:
        stale = [n for n, b in files.items() if not (out / n).exists() or (out / n).read_bytes() != b]
        if stale:
            print(f"stale in {out}: {stale}")
            return 1
        print(f"docs/release/{a.version} current ({len(files)} generated files)")
        return 0
    out.mkdir(parents=True, exist_ok=True)
    for n, b in files.items():
        (out / n).write_bytes(b)
    print(f"wrote {len(files)} files to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
