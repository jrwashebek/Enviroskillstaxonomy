#!/usr/bin/env python3
"""Regenerate the status block in README.md from the data (LMPs pattern; ADR-0021: counts are computed, never typed).

Usage: python scripts/update_readme_status.py           # rewrite the block between the status markers
       python scripts/update_readme_status.py --check   # exit 1 if the block is stale
"""
from __future__ import annotations

import argparse
import re
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import emstlib as L  # noqa: E402

START, END = "<!-- status:start -->", "<!-- status:end -->"
README = L.ROOT / "README.md"


def status_lines(data_root: Path = L.DATA_V2) -> list[str]:
    recs = {}
    for loc, rec in L.iter_records(data_root):
        if isinstance(rec, dict) and isinstance(rec.get("id"), str):
            recs.setdefault(rec["id"], (loc, rec))
    hold = L.load_yaml(data_root / "governance" / "tribal_hold.yaml") if (data_root / "governance" / "tribal_hold.yaml").exists() else {}
    held_keys = set(hold.get("heldSeedKeys") or [])

    def held(rid, r):
        return rid in held_keys or (r.get("indigenousDataFlag") is True and r.get("approvalStatus") != "approved")

    by_type = Counter(r.get("type") for _, r in recs.values())
    comps = [(rid, r) for rid, (_, r) in recs.items() if r.get("type") == "Competency"]
    live = [(rid, r) for rid, r in comps if r.get("status") not in ("superseded", "withdrawn")]
    live_core = [x for x in live if x[1].get("module") == "core" and not held(*x)]
    seed = Counter("v1 seed (unauthored)" if r.get("validationStatus") == "seed-v1" else "authored" for _, r in live)
    by_module = Counter(r.get("module") for _, r in live if not held(_, r))
    reg = data_root / "ids" / "registry.csv"
    minted = max(0, len(reg.read_text(encoding="utf-8").splitlines()) - 1) if reg.exists() else 0
    x1 = data_root / "crosswalks" / "emst-v1" / "emst-v1_to_v2.sssom.tsv"
    x1_subjects = set()
    x1_rows = 0
    if x1.exists():
        for ln in x1.read_text(encoding="utf-8").splitlines()[1:]:
            if ln.strip():
                x1_rows += 1
                x1_subjects.add(ln.split("\t", 1)[0])
    v1_prior = sum(1 for _, r in recs.values() if r.get("raterType") == "v1-analyst")
    held_n = sum(1 for rid, (_, r) in recs.items() if held(rid, r))
    lines = [
        "## Status (generated)",
        "",
        f"Generated by `scripts/update_readme_status.py` from `data/v2/` (schema {L.SCHEMA_VERSION}). Do not edit by hand.",
        "",
        "| Measure | Value |",
        "|---|---|",
        f"| Source records | {len(recs)} |",
        f"| Live competencies (draft or later, not held) | {len(live) - sum(1 for x in live if held(*x))} |",
        f"| … of which in core | {len(live_core)} |",
        f"| … v1 seeds not yet authored / authored | {seed.get('v1 seed (unauthored)', 0)} / {seed.get('authored', 0)} |",
        f"| Tasks | {by_type.get('Task', 0)} |",
        f"| v1 prior-evidence ratings (`raterType: v1-analyst`) | {v1_prior} |",
        f"| Held Tribal-related records (count only; ADR-0007 §D) | {held_n} |",
        f"| Minted persistent IDs (`data/v2/ids/registry.csv`) | {minted} |",
        f"| Records at `candidate` (minted; what a release build may publish) | {sum(1 for _, r in recs.values() if r.get('status') == 'candidate')} |",
        f"| X1 v1→v2 rows / v1 keys covered | {x1_rows} / {len(x1_subjects)} |",
        "",
        "Records by type: " + ", ".join(f"{t} {n}" for t, n in sorted(by_type.items())) + ".",
        "",
        "Live competencies by module: " + ", ".join(f"{m} {n}" for m, n in sorted(by_module.items())) + ".",
    ]
    return lines


def render(text: str, lines: list[str]) -> str:
    block = START + "\n" + "\n".join(lines) + "\n" + END
    if START in text and END in text:
        return re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _m: block, text, flags=re.S)
    return text.rstrip("\n") + "\n\n" + block + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = README.read_text(encoding="utf-8")
    new = render(text, status_lines())
    if args.check:
        if new != text:
            print("README status block is stale: run python scripts/update_readme_status.py")
            return 1
        print("README status block is current")
        return 0
    README.write_text(new, encoding="utf-8")
    print("\n".join(status_lines()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
